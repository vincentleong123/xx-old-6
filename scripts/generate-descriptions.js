const fs = require('fs');
const path = require('path');

const DB_PATH = path.join(__dirname, '..', 'data', 'database.json');
const DESC_PATH = path.join(__dirname, '..', 'data', 'video-descriptions.json');

if (!fs.existsSync(DB_PATH)) {
  console.error('database.json not found');
  process.exit(1);
}

console.log('Loading database.json...');
const db = JSON.parse(fs.readFileSync(DB_PATH, 'utf8'));
const videosCol = db.collections.find(c => c.name === 'videos');
if (!videosCol) {
  console.error('No videos collection found');
  process.exit(1);
}

const videos = videosCol.data;
console.log(`Loaded ${videos.length} videos from database.json`);

// Load existing descriptions to preserve keywords
let existingDescs = {};
if (fs.existsSync(DESC_PATH)) {
  const raw = JSON.parse(fs.readFileSync(DESC_PATH, 'utf8'));
  existingDescs = raw.descriptions || raw;
  console.log(`Loaded ${Object.keys(existingDescs).length} existing descriptions`);
}

const nlpWriter = require('../utils/nlp-writer');

console.log('\nGenerating rich descriptions for all videos...');
const startTime = Date.now();

const newDescriptions = {};
let count = 0;

for (const video of videos) {
  count++;
  if (count % 500 === 0) {
    console.log(`  Processing ${count}/${videos.length}...`);
  }

  // Build video object for NLP writer
  const videoForNlp = {
    id: video.id,
    title: video.title || video.name || video.id,
    subTags: video.subTags || [],
    keywords: video.keywords || [],
    category: video.category || 'Malay Adult'
  };

  // Find related videos from same category
  const category = nlpWriter.classifyVideo(videoForNlp);
  const related = videos
    .filter(v => v.id !== video.id && nlpWriter.classifyVideo({
      id: v.id, title: v.title || v.name || v.id,
      subTags: v.subTags || [], keywords: v.keywords || []
    }) === category)
    .slice(0, 6);

  const article = nlpWriter.generateFullArticle(videoForNlp, related);

  // Merge with existing description data (preserve keywords)
  const existing = existingDescs[video.id] || {};

  newDescriptions[video.id] = {
    text: article.fullHtml,
    keywords: existing.keywords || video.keywords || [],
    autoGenerated: true,
    proGenerated: true,
    category: article.category,
    generatedAt: new Date().toISOString(),
    updatedAt: new Date().toISOString()
  };
}

const elapsed = ((Date.now() - startTime) / 1000).toFixed(1);
console.log(`\nGenerated ${Object.keys(newDescriptions).length} descriptions in ${elapsed}s`);

// Calculate stats
const lengths = Object.values(newDescriptions).map(d => d.text.length);
const avgLen = Math.round(lengths.reduce((a, b) => a + b, 0) / lengths.length);
const minLen = Math.min(...lengths);
const maxLen = Math.max(...lengths);
console.log(`Description length: avg=${avgLen} chars, min=${minLen}, max=${maxLen}`);

// Write output
const output = { descriptions: newDescriptions };
fs.writeFileSync(DESC_PATH, JSON.stringify(output, null, 2));
console.log(`\nWrote ${DESC_PATH}`);
console.log(`\nDone! Restart server to see changes.`);
