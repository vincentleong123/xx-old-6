const fs = require('fs');
const path = require('path');

const DB_PATH = path.join(__dirname, '..', 'data', 'database.json');
const DESC_PATH = path.join(__dirname, '..', 'data', 'video-descriptions.json');

if (!fs.existsSync(DB_PATH)) {
  console.error('database.json not found');
  process.exit(1);
}

const db = JSON.parse(fs.readFileSync(DB_PATH, 'utf8'));
const videosCol = db.collections.find(c => c.name === 'videos');
if (!videosCol) { console.error('No videos collection'); process.exit(1); }

const videos = videosCol.data;
console.log(`Loaded ${videos.length} videos`);

const aiWriter = require('../utils/ai-writer');

const newDescriptions = {};
let count = 0;
const seenTexts = new Set();

for (const video of videos) {
  count++;
  if (count % 1000 === 0) console.log(`  ${count}/${videos.length}...`);

  const result = aiWriter.generateDescription(video, []);

  let text = result.text;
  let attempts = 0;
  while (seenTexts.has(text) && attempts < 10) {
    text = text.replace(/\.$/, '') + ' #' + (attempts + 1) + '.';
    attempts++;
  }
  seenTexts.add(text);

  newDescriptions[video.id] = {
    text,
    keywords: result.keywords.length > 0 ? result.keywords : (video.keywords || []),
    autoGenerated: true,
    category: video.category || 'Malay Amateur',
    generatedAt: new Date().toISOString()
  };
}

const lengths = Object.values(newDescriptions).map(d => d.text.length);
const avgLen = Math.round(lengths.reduce((a, b) => a + b, 0) / lengths.length);

const output = { descriptions: newDescriptions };
fs.writeFileSync(DESC_PATH, JSON.stringify(output, null, 2));
console.log(`\nDone! ${Object.keys(newDescriptions).length} descriptions, avg ${avgLen} chars`);
console.log(`Unique texts: ${newDescriptions.size || Object.keys(newDescriptions).length}`);
